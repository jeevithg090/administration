import path from 'node:path';

export const IMAGE_EXTENSIONS = ['.jpg', '.jpeg', '.png', '.gif', '.webp'] as const;
export const AUDIO_EXTENSIONS = ['.mp3', '.wav', '.ogg', '.m4a', '.aac'] as const;

export const MIN_IMAGE_DURATION = 0.5;
export const MAX_IMAGE_DURATION = 10;
export const MAX_IMAGES = 20;
export const MAX_DESCRIPTION_LENGTH = 1000;
export const MAX_SCRIPT_LENGTH = 2500;

export type VideoQuality = '720p' | '1080p';

export const VIDEO_DIMENSIONS: Record<VideoQuality, { width: number; height: number }> = {
  '720p': { width: 1280, height: 720 },
  '1080p': { width: 1920, height: 1080 },
};

const UUID = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}';
const STORED_IMAGE_RE = new RegExp(`^${UUID}\\.(jpe?g|png|gif|webp)$`);
const UUID_RE = new RegExp(`^${UUID}$`);

/** True for an id generated by the server (v4 UUID, lowercase). */
export function isJobId(value: unknown): value is string {
  return typeof value === 'string' && UUID_RE.test(value);
}

/**
 * True for a filename the upload handler could have produced. This is the
 * only thing standing between client input and the filesystem, so it is
 * deliberately strict: no separators, no dot segments, known extensions only.
 */
export function isStoredImageName(value: unknown): value is string {
  return typeof value === 'string' && STORED_IMAGE_RE.test(value);
}

/** Normalised, lowercase extension if it is in the allow-list, otherwise null. */
export function allowedExtension(originalName: string, allowed: readonly string[]): string | null {
  const ext = path.extname(originalName).toLowerCase();
  return allowed.includes(ext) ? ext : null;
}

export interface CreateVideoOptions {
  imageFiles: string[];
  duration: number;
  useTransitions: boolean;
  videoQuality: VideoQuality;
}

export type ParseResult<T> = { ok: true; value: T } | { ok: false; error: string };

export function parseCreateVideoBody(body: unknown): ParseResult<CreateVideoOptions> {
  if (typeof body !== 'object' || body === null) {
    return { ok: false, error: 'Request body must be a JSON object' };
  }
  const input = body as Record<string, unknown>;

  const { imageFiles } = input;
  if (!Array.isArray(imageFiles) || imageFiles.length === 0) {
    return { ok: false, error: 'No image files provided' };
  }
  if (imageFiles.length > MAX_IMAGES) {
    return { ok: false, error: `At most ${MAX_IMAGES} images are allowed` };
  }
  if (!imageFiles.every(isStoredImageName)) {
    return { ok: false, error: 'Invalid image file reference' };
  }

  const duration = input.duration === undefined ? 2 : Number(input.duration);
  if (
    !Number.isFinite(duration) ||
    duration < MIN_IMAGE_DURATION ||
    duration > MAX_IMAGE_DURATION
  ) {
    return {
      ok: false,
      error: `Duration must be between ${MIN_IMAGE_DURATION} and ${MAX_IMAGE_DURATION} seconds`,
    };
  }

  const videoQuality = input.videoQuality ?? '720p';
  if (videoQuality !== '720p' && videoQuality !== '1080p') {
    return { ok: false, error: 'videoQuality must be "720p" or "1080p"' };
  }

  return {
    ok: true,
    value: {
      imageFiles,
      duration,
      useTransitions: input.useTransitions !== false,
      videoQuality,
    },
  };
}

/** Trim and validate a free-text field. */
export function parseText(value: unknown, field: string, maxLength: number): ParseResult<string> {
  if (typeof value !== 'string' || value.trim() === '') {
    return { ok: false, error: `${field} is required` };
  }
  const trimmed = value.trim();
  if (trimmed.length > maxLength) {
    return { ok: false, error: `${field} must be at most ${maxLength} characters` };
  }
  return { ok: true, value: trimmed };
}
